# show help and usage
progname=`basename $0`
showHelp()
{
cat << EndHelpHeader
Script for testing PX and proxy renewal functions

Deposits the tester's proxy with the MyProxy server, asks glite-proxy-renew to keep
it renewed, waits, and compares what came back with what was put in. Then does the
same again with a freshly issued proxy to show that the deposit was replaced and not
merely returned, and finally looks at how big a set of VOMS attributes the renewal
survives.

Prerequisities:
   - MyProxy server running on the testbed, accepting deposits from the test CA
   - glite-proxy-renew, myproxy-init and myproxy-store installed
   - a VOMS server for the VO, for the attribute-size check at the end
   - credentials generated by 'make -C tools' and a testbed from setup.sh

The run takes PX_RENEWAL_WAIT seconds (1800 by default) because the renewal daemon
has to notice the deposit on its own; PX_RENEWAL_WAIT says how long to wait.

Returned values:
    Exit TEST_OK: Test Passed
    Exit TEST_ERROR: Test Failed
    Exit 2: Wrong Input

EndHelpHeader

	echo "Usage: $progname [OPTIONS]"
	echo "Options:"
	echo " -h | --help            Show this help message."
	echo " -o | --output 'file'   Redirect all output to the 'file' (stdout by default)."
	echo " -t | --text            Format output as plain ASCII text."
	echo " -c | --color           Format output as text with ANSI colours (autodetected by default)."
	echo " -x | --html            Format output as html."
}

# read common definitions and functions
COMMON=`dirname $0`/px-common.sh
if [ ! -r ${COMMON} ]; then
        printf "Common definitions '${COMMON}' missing!\n"
        exit 2
fi
source $COMMON

logfile=$$.tmp
flag=0
# This script's own, not from the library: a newline in text and a <br> in HTML, for
# the lines of report text that continue on the next line. (It is what the library's
# $lf does, without the extra newline HTML mode adds.)
NL="\n"
while test -n "$1"
do
	case "$1" in
		"-h" | "--help") showHelp && exit 2 ;;
		"-o" | "--output") shift ; logfile=$1 flag=1 ;;
		"-t" | "--text")  setOutputASCII ;;
		"-c" | "--color") setOutputColor ;;
		"-x" | "--html")  setOutputHTML ; NL="<br>" ;;
	esac
	shift
done

DEBUG=2

##
#  Starting the test
#####################

{
test_start


# check_binaries
printf "Testing if all binaries are available"
# What this script actually runs. The list used to name curl, rm, chown, wget and
# sleep - several of which it never calls - while leaving out the two programs whose
# absence makes the whole test meaningless.
check_binaries voms-proxy-info voms-proxy-init glite-proxy-renew myproxy-init openssl date make
if [ $? -gt 0 ]; then
	test_failed
	test_end
	exit 2
else
	test_done
fi

# The proxy that gets deposited is the tester's own, from 'make -C tools'. It used to
# be made here if it was missing - check_credentials_and_generate_proxy - which is why
# the variables below were spelled $x509_USER_CERT: the deleted generator exported
# that misspelled pair, and nothing else ever did. Generating credentials in the
# middle of a run also meant a testbed with no credentials could still pass.
printf "Testing credentials"
if ! need_credentials; then
	test_end
	exit 2
fi
if [ ! -r "$X509_USER_CERT" ] || [ ! -r "$X509_USER_KEY" ]; then
	print_error "No user certificate in $X509_USER_CERT and $X509_USER_KEY"
	test_end
	exit 2
fi

printf "User Cert $X509_USER_CERT$NL"
printf "User Key $X509_USER_KEY$NL"
chmod 600 "$X509_USER_CERT" "$X509_USER_KEY"

# MyProxy identifies the server by the DN of its certificate rather than by its name,
# and refuses the connection when what it is offered does not match. px-common.sh
# takes it from the testbed setup; reading it here is the fallback for a run by hand.
if [ -z "$MYPROXY_SERVER_DN" ]; then
	MYPROXY_SERVER_DN=`credentials_dn "$MYPROXY_HOST_CERT"`
fi
if [ -z "$MYPROXY_SERVER_DN" ]; then
	test_failed
	print_error "Cannot tell which certificate $PX_SERVER presents - no readable host certificate in $MYPROXY_HOST_CERT"
	test_end
	exit 2
fi
export MYPROXY_SERVER_DN
printf "MyProxy server DN $MYPROXY_SERVER_DN$NL"

JOBID=https://fake.job.id/xxx

ORIG_PROXY=`voms-proxy-info | grep -E "^path" | sed 's/^path\s*:\s*//'`
PROXYDN=`voms-proxy-info | grep -E "^identity" | sed 's/^identity\s*:\s*//'`
printf "Registering proxy by calling myproxy-init -s $PX_SERVER -d -n --certfile $X509_USER_CERT --keyfile $X509_USER_KEY$NL"
myproxy-init -s "$PX_SERVER" -d -n --certfile "$X509_USER_CERT" --keyfile "$X509_USER_KEY"

printf "Getting registered proxy... "
REGISTERED_PROXY=`glite-proxy-renew -s "$PX_SERVER" -f "$ORIG_PROXY" -j $JOBID start`

if [ "$REGISTERED_PROXY" = "" ]; then
	test_failed
	print_error "Could not set renewal"
	test_end
	exit $TEST_ERROR
fi
test_done

printf "\tProxy:\t$ORIG_PROXY$NL\tRenew:\t$REGISTERED_PROXY$NL"

printf "Checking key lengths...$NL"
ORIGLENGTH=`voms-proxy-info -file "$ORIG_PROXY" | grep strength | grep -E -o "[0-9]+"`
REGISTEREDLENGTH=`voms-proxy-info -file "$REGISTERED_PROXY" | grep strength | grep -E -o "[0-9]+"`

printf "Original proxy key: $ORIGLENGTH bits "
if [ "$ORIGLENGTH" -lt "1024" ]; then
	test_failed
else
	test_done
fi
printf "Registered proxy key: $REGISTEREDLENGTH bits "
if [ "$REGISTEREDLENGTH" -lt "1024" ]; then
	test_failed
else
	test_done
fi

printf "Checking time left on registered proxy... "
REGISTEREDTIMELEFT=`voms-proxy-info -file "$REGISTERED_PROXY" | grep timeleft | grep -E -o "[0-9]+:[0-9]+:[0-9]+"`
#Use this for conversion: date --utc --date "1970-1-1 0:0:0" +%s
REGISTEREDTIMELEFTSEC=`date --utc --date "1970-1-1 $REGISTEREDTIMELEFT" +%s`
printf "($REGISTEREDTIMELEFT, i.e. $REGISTEREDTIMELEFTSEC s)"
if [ ! $REGISTEREDTIMELEFTSEC -gt 0 ]; then
	test_failed
	print_error "Failed to retrieve time left"
	test_end
	exit $TEST_ERROR
fi
test_done

# The wait is the test: the renewal happens when the daemon next looks at the
# deposit, and nothing a client can do hurries that up. PX_RENEWAL_WAIT is how long
# the deployment is expected to take; the sleep used to be a hardcoded 1805.
printf "sleeping %s (Sorry, no other way to let the proxy age enough)... " "$PX_RENEWAL_WAIT"
sleep "$PX_RENEWAL_WAIT"
test_done


printf "Checking time left on registered proxy... "
REGISTEREDTIMELEFT=`voms-proxy-info -file "$REGISTERED_PROXY" | grep timeleft | grep -E -o "[0-9]+:[0-9]+:[0-9]+"`
REGISTEREDTIMELEFTSEC=`date --utc --date "1970-1-1 $REGISTEREDTIMELEFT" +%s`
printf "($REGISTEREDTIMELEFT, i.e. $REGISTEREDTIMELEFTSEC s)"
if [ ! $REGISTEREDTIMELEFTSEC -gt 0 ]; then
	test_failed
	print_error "Failed to retrieve time left"
	test_end
	exit $TEST_ERROR
fi
test_done

printf "Checking time left on original proxy... "
ORIGINALTIMELEFT=`voms-proxy-info -file "$ORIG_PROXY" | grep timeleft | grep -E -o "[0-9]+:[0-9]+:[0-9]+"`
ORIGINALTIMELEFTSEC=`date --utc --date "1970-1-1 $ORIGINALTIMELEFT" +%s`
printf "($ORIGINALTIMELEFT, i.e. $ORIGINALTIMELEFTSEC s)"
if [ ! $ORIGINALTIMELEFTSEC -gt 0 ]; then
	test_failed
	print_error "Failed to retrieve time left"
	test_end
	exit $TEST_ERROR
fi
test_done

printf "Checking renewal ($REGISTEREDTIMELEFTSEC > $ORIGINALTIMELEFTSEC)? "
expr $REGISTEREDTIMELEFTSEC \> $ORIGINALTIMELEFTSEC > /dev/null
if [ $? -eq 0 ]; then
	test_done
else
	test_failed
	print_error "Proxy was not renewed"
fi

printf "Other particulars:$NL"
printf "Registered proxy `voms-proxy-info -file "$REGISTERED_PROXY" -fqan -actimeleft`$NL"
printf "Original proxy `voms-proxy-info -file "$ORIG_PROXY" -fqan -actimeleft`$NL"
printf "Registered proxy `voms-proxy-info -file "$REGISTERED_PROXY" -identity`$NL"
printf "Original proxy `voms-proxy-info -file "$ORIG_PROXY" -identity`$NL"

printf "Checking if test uses fake proxy... "
voms-proxy-info | grep -E "^subject.*.L=Tropic.O=Utopia.OU=Relaxation" > /dev/null
if [ $? -eq 0 ]; then
	printf "yes."
	test_done
	printf "Generating new proxy... "
	# The renewal has to be shown to replace the deposit rather than keep serving
	# the one it was given, which means putting a different proxy at the same path
	# while the registration is alive. That is what the tools generator does -
	# the same 'make -C tools proxy' the tester ran before the run, with the short
	# lifetime this test wants.
	if px_regen_proxy > /dev/null; then
		test_done
		printf "Registering new proxy for renewal (regression into Savannah Bug #90610)... "
		NEW_REGISTERED=`glite-proxy-renew -s "$PX_SERVER" -f "$ORIG_PROXY" -j $JOBID start`
		if [ "$NEW_REGISTERED" == "$REGISTERED_PROXY" ]; then
			test_done
			printf "Checking time left on new proxy... "
			NEWTIMELEFT=`voms-proxy-info -file "$REGISTERED_PROXY" | grep timeleft | grep -E -o "[0-9]+:[0-9]+:[0-9]+"`
			NEWTIMELEFTSEC=`date --utc --date "1970-1-1 $NEWTIMELEFT" +%s`
			printf "$NEWTIMELEFT ($NEWTIMELEFTSEC)"
			test_done
			printf "Checking if old proxy ($REGISTEREDTIMELEFTSEC) was replaced by new ($NEWTIMELEFTSEC)... "
			expr $NEWTIMELEFTSEC \> $REGISTEREDTIMELEFTSEC > /dev/null
			if [ $? -eq 0 ]; then
				test_done
			else
				test_failed
				print_error "Proxy was not replaced"
			fi

			printf "Checking key length for the new proxy... "
			NEWLENGTH=`voms-proxy-info -file "$NEW_REGISTERED" | grep strength | grep -E -o "[0-9]+"`
			printf "New proxy key: $NEWLENGTH bits "
			if [ "$NEWLENGTH" -lt "1024" ]; then
				test_failed
			else
				test_done
			fi
		else
			test_failed
			print_error "Not created as the same registration!${NL}Old proxy: $REGISTERED_PROXY${NL}New proxy: $NEW_REGISTERED"
		fi
		printf "Removing 2nd registration... "
		glite-proxy-renew -j $JOBID stop;
		if [ $? -eq 0 ]; then
			test_done
		else
			test_failed
			print_error "Failed to stop"
		fi

	else
		test_failed
		print_error "Failed to generate proxy - make -C $TESTSUITE_HOME/tools proxy PROXY=$X509_USER_PROXY"
	fi


else
	printf "no."
	test_skipped
fi


printf "Stopping renewal... "
glite-proxy-renew -j $JOBID stop;
if [ $? -eq 0 ]; then
	test_done
else
	test_failed
	print_error "Failed to stop"
fi


printf "Checking if registered proxy was removed... "
if [ -f "$REGISTERED_PROXY" ]; then
	test_failed
	print_error "Registered proxy still exists ($REGISTERED_PROXY)"
else
	test_done
fi

UTOPIA=`voms-proxy-info -all | grep -A 100 "extension information" | grep "^issuer" | grep "L=Tropic" | grep "O=Utopia" | grep "OU=Relaxation"`
if [ "$UTOPIA" != "" ]; then
	printf "Possibly fake VOMS extensions. Regenerating... "
	voms-proxy-init -voms "$PX_VO" -key "$X509_USER_KEY" -cert "$X509_USER_CERT" | sed "s/\$/$NL/"
fi


printf "Checking VOMS attributes size to decide if it's possible to determine the status of bug #92806 (regression into bug #92806)... "
attrsize=`voms-proxy-info -all | grep ^attribute | sed -r 's/attribute\s*:\s*//' | wc -c`
if [ "$attrsize" == "" ]; then
	attrsize=0
fi
if [ $attrsize -gt 1024 ]; then
	printf "Registering proxy for renewal"
	ORIG_PROXY=`voms-proxy-info | grep -E "^path" | sed 's/^path\s*:\s*//'`
	REGISTERED=`glite-proxy-renew -s "$PX_SERVER" -f "$ORIG_PROXY" -j $JOBID start`

	if [ "$REGISTERED" = "" ]; then
		printf "failed to renew with $attrsize bytes of attributes"
		test_failed
		print_error "Could not set renewal"
	else
		printf "renewed with $attrsize bytes of attributes"
		test_done

		printf "Stopping renewal... "
		glite-proxy-renew -j $JOBID stop;
		if [ $? -eq 0 ]; then
			test_done
		else
			test_failed
			print_error "Failed to stop"
		fi

	fi
else
	printf "only $attrsize bytes of attributes"
	test_skipped
fi



test_end
} &> $logfile

if [ $flag -ne 1 ]; then
	cat $logfile
	$SYS_RM $logfile
fi
exit $TEST_OK
